<?php

/**
 * Общий bootstrap для всех наборов тестов.
 */

require_once __DIR__ . '/../vendor/autoload.php';

// App\Database — синглтон, и параметры соединения он читает в конструкторе, то есть
// ровно один раз за процесс. Значит подменить базу можно только здесь, до того как
// любой тест дотянется до первой модели.
//
// Значение по умолчанию — тестовое, а не рабочее: интеграционный тест, забывший
// объявить о своих намерениях, должен упасть на отсутствующей базе, а не молча
// вычистить `telegram_bot` через TRUNCATE в setUp.
if (getenv('DB_NAME') === false) {
    putenv('DB_NAME=telegram_bot_test');
}

// Тесты не должны зависеть от часового пояса машины: dayLabel, границы периодов
// и `date('Y-m-d')` в ExpenseConfirmation считаются от него.
date_default_timezone_set('UTC');

// Половина проверяемых веток — это обработка сбоев, а каждая из них пишет в
// error_log. По умолчанию он идёт в stderr и растворяет результат прогона в
// десятке строк «Gemini request failed». Уводим в файл: сообщения никуда
// не деваются, но не мешают читать вывод.
ini_set('error_log', __DIR__ . '/../.phpunit.cache/tests-error.log');
