<?php

namespace App\Controllers\Handlers;

use App\Models\User;
use TelegramBot\Api\Client;
use TelegramBot\Api\Types\ReplyKeyboardMarkup;
use TelegramBot\Api\Types\Update;

/**
 * Обрабатывает команды /start и /help
 */
class StartHandler
{
    /**
     * Клавиатура бота: подпись кнопки → команда, в которую её превращает
     * {@see \App\Bot::handleUpdate()}.
     *
     * Карта живёт здесь, а не в Bot: клавиатуру рисует этот класс, и держать
     * подписи в двух местах — верный способ их рассинхронизировать. Нажатие
     * присылает обычный текст, поэтому подпись обязана быть уникальной и
     * непохожей на трату.
     *
     * Раньше сюда же попадали частые траты — кнопки вида «продукты 605» со
     * средней суммой. Убраны: среднее почти никогда не совпадает с реальной
     * покупкой (у «продуктов» разброс 44…3838, промах больше 15% в 96%
     * случаев), а записанная кнопкой правдоподобная, но неверная сумма портит
     * и статистику, и лимиты незаметно. Набрать «продукты 921» — одно
     * сообщение, и оно всегда верное.
     */
    public const CONTROLS = [
        '📊 Статистика' => '/stats',
        '🖥 Дашборд'    => '/web',
        '🎯 Лимиты'     => '/stats lim',
        '📋 Категории'  => '/categories list',
        '❓ Помощь'     => '/help',
    ];

    private Client $tg;
    private User $userModel;

    public function __construct(Client $tg)
    {
        $this->tg = $tg;
        $this->userModel = new User();
    }

    /**
     * Регистрирует пользователя при первом обращении и показывает приветствие.
     *
     * @param Update $update
     * @return void
     */
    public function handle(Update $update): void
    {
        $chatId = $update->getMessage()->getChat()->getId();

        if (!$this->userModel->exists($chatId)) {
            try {
                $this->userModel->register($chatId);
            } catch (\Exception $e) {
                error_log($e->getMessage());
                $this->tg->sendMessage($chatId, '❌ Произошла ошибка при регистрации.');
                return;
            }
        }

        $message = "👋 Бот учёта расходов.\n\n"
            . "💡 Отправляйте траты обычным сообщением:\n"
            . "• кофе 200\n"
            . "• такси 300, обед 450\n"
            . "Категория определится автоматически.\n\n"
            . "⌨️ Кнопки бота — значок команд справа от поля ввода.\n"
            . "Приложение — кнопка «Меню» слева от поля или /app.\n\n"
            . "📋 Команды:\n"
            . "/stats — статистика прямо в чате\n"
            . "/app — открыть приложение\n"
            . "/web — то же самое в браузере\n"
            . "/categories — управление категориями\n"
            . "/setlimit — лимит по категории\n"
            . "/setgloballimit — общий лимит";

        $this->tg->sendMessage($chatId, $message, null, false, null, $this->keyboard());
    }

    /**
     * Клавиатура бота — только навигация, пять кнопок в три ряда.
     *
     * «Дашборд» присылает текст, как и остальные, а ссылку в ответ уже шлёт
     * `/web`. Иначе и нельзя: кнопки этой клавиатуры url не поддерживают вовсе,
     * а ссылка всё равно своя у каждого чата и живёт неделю — в постоянную
     * разметку её не зашить.
     *
     * Одинакова для всех и не зависит от истории, поэтому перестраивать её
     * незачем: выставленная однажды, она живёт в чате до следующей смены.
     * Заодно из /start ушёл взвешенный GROUP BY по трём месяцам трат, который
     * считался ради шести подписей.
     *
     * Плейсхолдер поля ввода несёт формат: с уходом кнопок-трат набор текста
     * стал единственным способом записи, и подсказать его больше негде.
     *
     * `is_persistent` намеренно выключен. С ним клавиатуру нельзя свернуть, и
     * системная кнопка «назад» на Android переставала работать в чате с ботом:
     * закрывать ей было нечего, а до выхода из диалога дело не доходило.
     * Без него клавиатура сворачивается значком справа от поля ввода, а «назад»
     * ведёт себя как в любом другом чате.
     */
    private function keyboard(): ReplyKeyboardMarkup
    {
        return new ReplyKeyboardMarkup(
            array_chunk(array_keys(self::CONTROLS), 2),
            null,
            true,
            null,
            false,
            'кофе 200, такси 350'
        );
    }
}
