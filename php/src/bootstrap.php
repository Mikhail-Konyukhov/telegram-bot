<?php

/**
 * Общий bootstrap: подключается автозагрузчиком (`composer.json` → autoload.files),
 * поэтому одинаково отрабатывает для index.php, api.php, bin/worker.php и тестов.
 *
 * Часовой пояс PHP из переменной TZ не читает — только из ini, — и без него всё
 * считается в UTC. У пользователя в +06 это значило, что сутки в отчётах
 * начинались в шесть утра: трата, записанная ночью, попадала во вчерашний день,
 * а «Сегодня» в /stats до утра показывало вчера. Сам пояс задан в compose,
 * здесь он только доносится до PHP.
 */

date_default_timezone_set(getenv('TZ') ?: 'UTC');
